-- ============================================================
-- Sistema de restaurante: mesas, atendimentos, pedidos e pagamentos
-- SGBD: MySQL 8.0.16 ou superior (CHECK ativo)
-- Registros de teste: 20 mesas + 50 produtos + 220 atendimentos
--                   + 600 pedidos + 250 pagamentos = 1.140 registros
-- Observacao: DECIMAL e utilizado para valores monetarios, evitando
-- imprecisao de ponto flutuante. IDs foram adicionados nas entidades
-- sem chave primaria explicita no DER original.
-- ============================================================

CREATE DATABASE IF NOT EXISTS restaurante_comandas
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE restaurante_comandas;

-- Tabelas independentes
CREATE TABLE mesa (
    numero SMALLINT UNSIGNED NOT NULL,
    ocupada BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_mesa PRIMARY KEY (numero),
    CONSTRAINT chk_mesa_numero CHECK (numero > 0)
) ENGINE=InnoDB;

CREATE TABLE produto (
    codigo INT UNSIGNED NOT NULL,
    nome VARCHAR(100) NOT NULL,
    preco DECIMAL(10,2) NOT NULL,
    disponivel BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_produto PRIMARY KEY (codigo),
    CONSTRAINT uq_produto_nome UNIQUE (nome),
    CONSTRAINT chk_produto_preco CHECK (preco > 0)
) ENGINE=InnoDB;

-- Tabelas dependentes
CREATE TABLE atendimento (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    mesa_numero SMALLINT UNSIGNED NOT NULL,
    encerrado BOOLEAN NOT NULL DEFAULT FALSE,
    total DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    total_pago DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    saldo DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    CONSTRAINT pk_atendimento PRIMARY KEY (id),
    CONSTRAINT fk_atendimento_mesa FOREIGN KEY (mesa_numero)
        REFERENCES mesa(numero) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_atendimento_valores CHECK (
        total >= 0 AND total_pago >= 0 AND saldo >= 0
        AND total_pago <= total
        AND saldo = total - total_pago
    )
) ENGINE=InnoDB;

CREATE TABLE pedido (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    atendimento_id BIGINT UNSIGNED NOT NULL,
    produto_codigo INT UNSIGNED NOT NULL,
    quantidade INT UNSIGNED NOT NULL,
    valor DECIMAL(10,2) NOT NULL,
    CONSTRAINT pk_pedido PRIMARY KEY (id),
    CONSTRAINT fk_pedido_atendimento FOREIGN KEY (atendimento_id)
        REFERENCES atendimento(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_pedido_produto FOREIGN KEY (produto_codigo)
        REFERENCES produto(codigo) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_pedido_quantidade CHECK (quantidade > 0),
    CONSTRAINT chk_pedido_valor CHECK (valor > 0)
) ENGINE=InnoDB;

CREATE TABLE pagamento (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    atendimento_id BIGINT UNSIGNED NOT NULL,
    valor DECIMAL(10,2) NOT NULL,
    CONSTRAINT pk_pagamento PRIMARY KEY (id),
    CONSTRAINT fk_pagamento_atendimento FOREIGN KEY (atendimento_id)
        REFERENCES atendimento(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_pagamento_valor CHECK (valor > 0)
) ENGINE=InnoDB;

